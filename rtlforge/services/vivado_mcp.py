"""Narrow synthesis adapter to AMD Ross's official stdio MCP server."""

from __future__ import annotations

import asyncio
import json
import os
import re
import traceback
from datetime import timedelta
from hashlib import sha256
from pathlib import Path
from time import monotonic

from rtlforge.domain.synthesis import SynthesisConstraints, SynthesisResult


def tcl_word(value: str | Path) -> str:
    """One literal Tcl word, including paths with spaces, braces or dollar signs."""
    value = str(value).replace("\\", "/")
    return '"' + value.replace("$", "\\$").replace("[", "\\[").replace(
        '"', '\\"'
    ).replace("\n", "\\n").replace("\r", "\\r") + '"'


def write_synthesis_script(directory: Path, rtl: Path, constraints: SynthesisConstraints,
                           dependencies=()):
    xdc = directory / "constraints.xdc"
    if constraints.xdc_path:
        xdc.write_bytes(Path(constraints.xdc_path).read_bytes())
    elif constraints.clock_port and constraints.clock_period_ns is not None:
        xdc.write_text(
            f"create_clock -name user_clock -period {constraints.clock_period_ns} "
            f"[get_ports {tcl_word(constraints.clock_port or '')}]\n",
            encoding="utf-8",
        )
    else:
        xdc.write_text("# Synthesis only; no timing acceptance was requested.\n", encoding="utf-8")
    # The script and all output paths are generated by the executor, never by the LLM.
    body = [
        *(f"read_verilog -sv {tcl_word(path)}" for path in (rtl, *dependencies)),
        f"read_xdc {tcl_word(xdc)}",
        f"synth_design -top {tcl_word(constraints.top or '')} "
        f"-part {tcl_word(constraints.part or '')} -mode out_of_context",
        f"report_utilization -file {tcl_word(directory / 'utilization.rpt')}",
        f"report_timing_summary -report_unconstrained "
        f"-file {tcl_word(directory / 'timing.rpt')}",
        f"report_timing -max_paths 3 -file {tcl_word(directory / 'critical_paths.rpt')}",
        f"check_timing -verbose -file {tcl_word(directory / 'check_timing.rpt')}",
        f"write_checkpoint -force {tcl_word(directory / 'synth.dcp')}",
        f"set metrics [open {tcl_word(directory / 'metrics.tsv')} w]",
        'puts $metrics "vivado_version\t[version -short]"',
        'puts $metrics "clock_count\t[llength [get_clocks -quiet]]"',
        "set paths [get_timing_paths -quiet -max_paths 1 -delay_type max]",
        'if {[llength $paths]} {puts $metrics "wns_ns\t[get_property SLACK $paths]"}',
        "close $metrics",
    ]
    script = directory / "synth.tcl"
    script.write_text(
        "if {[catch {\n" + "\n".join(body) + "\n} failure options]} {\n"
        f"set fd [open {tcl_word(directory / 'failure.txt')} w]\n"
        "puts $fd $failure\nclose $fd\n}\n"
        f"set fd [open {tcl_word(directory / 'finished.txt')} w]\nputs $fd done\nclose $fd\n",
        encoding="utf-8",
    )
    return script, xdc


def parse_reports(directory: Path, result: SynthesisResult) -> SynthesisResult:
    failure = directory / "failure.txt"
    if failure.exists():
        message = failure.read_text(encoding="utf-8", errors="replace")[:4000]
        result.diagnostics = message.splitlines()[:12]
        messages = directory / "vivado_messages.json"
        if messages.is_file():
            payload = json.loads(messages.read_text(encoding="utf-8"))
            result.diagnostics.extend(
                item["text"][:3000] for item in payload.get("content", [])[:3]
                if isinstance(item.get("text"), str)
            )
        infrastructure = re.search(
            r"license|not a valid part|specified part could not|not found.*part", message, re.I,
        )
        result.status = "ERROR" if infrastructure else "FAIL"
        result.category = "SYNTHESIS_TOOL_ERROR" if infrastructure else "SYNTHESIS_ERROR"
        result.synthesis_status = "ERROR" if infrastructure else "FAIL"
        return result
    required = ("metrics.tsv", "utilization.rpt", "timing.rpt", "check_timing.rpt", "synth.dcp")
    if not all((directory / name).is_file() for name in required):
        result.diagnostics = ["Vivado finished without a complete report/checkpoint set"]
        return result
    metrics = dict(
        line.split("\t", 1) for line in (directory / "metrics.tsv").read_text().splitlines()
        if "\t" in line
    )
    report = (directory / "utilization.rpt").read_text(errors="replace")
    names = {
        "lut": r"(?:Slice|CLB) LUTs\*?",
        "ff": r"(?:Slice|CLB) Registers",
        "bram": r"Block RAM Tile",
        "dsp": r"DSPs?",
    }
    for key, label in names.items():
        match = re.search(r"\|\s*" + label + r"\s*\|\s*([\d,.]+)\s*\|", report)
        if match:
            result.resources[key] = float(match[1].replace(",", ""))
    result.synthesis_status = "PASS"
    critical = directory / "critical_paths.rpt"
    if critical.is_file():
        text = critical.read_text(errors="replace")
        start = text.find("Slack (")
        result.critical_path_summary = text[max(0, start):][:4000]
    result.vivado_version = metrics.get("vivado_version")
    result.wns_ns = float(metrics["wns_ns"]) if metrics.get("wns_ns") else None
    check = (directory / "check_timing.rpt").read_text(errors="replace")
    # IO delays are intentionally outside a clock-only OOC core timing claim.
    no_clock = re.search(
        r"There (?:are|is) ([\d,]+) register/latch pins with no clock", check, re.I,
    )
    internal_sections = re.finditer(
        r"checking unconstrained_internal_endpoints(.*?)(?=\n\s*\d+\.\s*checking|\Z)",
        check, re.I | re.S,
    )
    # Vivado repeats the headings in a table of contents, without the diagnostic body.
    internal = next((
        count for section in internal_sections
        if (count := re.search(r"There (?:are|is) ([\d,]+) pins", section[1], re.I))
    ), None)
    counts = {
        "no_clock_register_pins": int(no_clock[1].replace(",", "")) if no_clock else None,
        "unconstrained_internal_endpoints": (
            int(internal[1].replace(",", "")) if internal else None
        ),
    }
    result.constraint_coverage = counts
    incomplete = any(value is not None and value > 0 for value in counts.values())
    known = all(value is not None for value in counts.values())
    clocked = int(metrics.get("clock_count", 0)) > 0
    result.constraints_status = (
        "INCOMPLETE" if incomplete or not clocked else "OOC_CORE_ONLY" if known else "UNKNOWN"
    )
    result.timing_status = (
        "NOT_EVALUATED" if result.wns_ns is None or result.constraints_status != "OOC_CORE_ONLY"
        else "PASS" if result.wns_ns >= 0 else "FAIL"
    )
    limits = result.constraints["resource_limits"]
    unknown = [key for key in limits if key not in result.resources]
    exceeded = [key for key, limit in limits.items() if result.resources.get(key, 0) > limit]
    result.resource_status = (
        "UNKNOWN" if unknown else "FAIL" if exceeded else "PASS" if limits else "NOT_REQUESTED"
    )
    if unknown:
        result.category = "SYNTHESIS_TOOL_ERROR"
        result.diagnostics.append("Missing resource metrics: " + ", ".join(unknown))
    elif exceeded:
        result.status, result.category = "FAIL", "SYNTHESIS_RESOURCE_EXCEEDED"
        result.diagnostics.append("Exceeded resource limits: " + ", ".join(exceeded))
    elif result.constraints["require_timing"] and result.timing_status == "NOT_EVALUATED":
        result.status, result.category = "FAIL", "SYNTHESIS_CONSTRAINT_ERROR"
        result.diagnostics.append("Core timing is not fully constrained or no timed path exists")
    elif result.constraints["require_timing"] and result.timing_status == "FAIL":
        result.status, result.category = "FAIL", "SYNTHESIS_TIMING_FAILED"
    else:
        result.status, result.category = "PASS", "OK"
    return result


class VivadoMCPRunner:
    def __init__(self, server_path: Path, vivado_path: Path, runs_root: Path, *, timeout=1800):
        self.server_path = Path(server_path).resolve()
        self.vivado_path = Path(vivado_path).resolve()
        self.runs_root = Path(runs_root).resolve()
        self.timeout = timeout

    def synthesize(self, context, candidate) -> SynthesisResult:
        from rtlforge.integration import dependency_files

        constraints = context.synthesis_constraints
        if constraints is None or constraints.missing():
            raise ValueError("Complete synthesis constraints are required")
        rtl = Path(candidate.artifact_path).resolve(strict=True)
        if not rtl.is_relative_to(self.runs_root):
            raise PermissionError("Synthesis may only read a candidate under this run root")
        digest = sha256(rtl.read_bytes()).hexdigest()
        if digest != candidate.code_hash:
            raise ValueError("Candidate hash mismatch before synthesis")
        parent = rtl.parent / "synthesis"
        attempt = 1
        while (directory := parent / f"attempt_{attempt:03d}").exists():
            attempt += 1
        directory.mkdir(parents=True)
        result = SynthesisResult(candidate.candidate_id, digest, constraints.to_dict())
        result.evidence = {"directory": str(directory)}
        try:
            if not self.server_path.is_file() or not self.vivado_path.is_file():
                raise FileNotFoundError("Configure existing Ross MCP Server and Vivado executable")
            result.mcp_server_sha256 = sha256(self.server_path.read_bytes()).hexdigest()
            dependencies = dependency_files(context)
            result.evidence["dependencies"] = [
                {"path": str(path), "sha256": sha256(path.read_bytes()).hexdigest()}
                for path in dependencies
            ]
            script, xdc = write_synthesis_script(directory, rtl, constraints, dependencies)
            result.evidence.update(
                script=str(script), xdc=str(xdc),
                xdc_sha256=sha256(xdc.read_bytes()).hexdigest(),
                mcp_calls=str(directory / "mcp_calls.jsonl"),
            )
            asyncio.run(self._run(directory, script, result))
            dependency_files(context)
            parse_reports(directory, result)
        except Exception as error:
            result.status, result.category = "ERROR", "SYNTHESIS_TOOL_ERROR"
            details = exception_messages(error)
            result.diagnostics.extend(details[:6])
            (directory / "adapter_error.log").write_text(traceback.format_exc(), encoding="utf-8")
        if sha256(rtl.read_bytes()).hexdigest() != digest:
            result.status, result.category = "ERROR", "SYNTHESIS_TOOL_ERROR"
            result.diagnostics.append("RTL changed during synthesis; reports invalidated")
        result.evidence.update({
            name: str(directory / name) for name in (
                "utilization.rpt", "timing.rpt", "check_timing.rpt", "synth.dcp",
                "critical_paths.rpt",
            ) if (directory / name).exists()
        })
        path = directory / "result.json"
        result.evidence["result"] = str(path)
        path.write_text(json.dumps(result.to_dict(), ensure_ascii=False, indent=2),
                        encoding="utf-8")
        return result

    async def _run(self, directory, script, result):
        from mcp import ClientSession, StdioServerParameters
        from mcp.client.stdio import stdio_client

        environment = {key: value for key, value in os.environ.items() if key in {
            "PATH", "SYSTEMROOT", "WINDIR", "TEMP", "TMP", "USERPROFILE", "APPDATA",
            "LOCALAPPDATA", "COMSPEC", "PATHEXT", "HOME", "XILINXD_LICENSE_FILE",
            "LM_LICENSE_FILE", "XILINX_VIVADO",
            "PROGRAMDATA", "ALLUSERSPROFILE", "HOMEDRIVE", "HOMEPATH", "USERNAME",
        }}
        environment["VIVADO_PATH"] = str(self.vivado_path)
        parameters = StdioServerParameters(
            command=str(self.server_path),
            args=["--stdio", f"--state-dir={directory / 'server_state'}"], env=environment,
            cwd=str(directory),
        )
        deadline = monotonic() + self.timeout
        with (directory / "mcp_server.stderr.log").open("w", encoding="utf-8") as errlog:
            async with stdio_client(parameters, errlog=errlog) as (read, write):
                async with ClientSession(
                    read, write, read_timeout_seconds=timedelta(seconds=60),
                ) as s:
                    initialized = await s.initialize()
                    result.mcp_server_info = initialized.serverInfo.model_dump(mode="json")
                    listing = await s.list_tools()
                    (directory / "mcp_tools.json").write_text(
                        listing.model_dump_json(indent=2), encoding="utf-8",
                    )
                    required = {"vivado_start", "vivado_execute", "vivado_status", "vivado_stop"}
                    if not required.issubset({tool.name for tool in listing.tools}):
                        raise RuntimeError("Ross server lacks required Vivado MCP tools")

                    async def call(name, args, *, cleanup=False):
                        remaining = 30 if cleanup else max(1, deadline - monotonic())
                        # Ross can keep source/synthesis synchronous. Its response may legitimately
                        # take longer than a short status request, up to the overall run deadline.
                        seconds = remaining if name == "vivado_execute" else min(remaining, 120)
                        try:
                            reply = await s.call_tool(
                                name, args, read_timeout_seconds=timedelta(seconds=seconds),
                            )
                        except Exception as error:
                            with (directory / "mcp_calls.jsonl").open("a", encoding="utf-8") as f:
                                f.write(json.dumps({"tool": name, "arguments": args,
                                                    "client_error": exception_messages(error)})
                                        + "\n")
                            raise
                        payload = reply.model_dump(mode="json", exclude_none=True)
                        with (directory / "mcp_calls.jsonl").open("a", encoding="utf-8") as stream:
                            stream.write(json.dumps({"tool": name, "arguments": args,
                                                     "response": payload}) + "\n")
                        if reply.isError:
                            raise RuntimeError(f"{name}: {str(payload)[:1500]}")
                        return payload

                    started = await call("vivado_start", {
                        "working_dir": str(directory), "session_type": "general",
                        "gui_mode": False, "vivado_path": str(self.vivado_path), "external": False,
                    })
                    session_id = find_session_id(started)
                    try:
                        await call("vivado_execute", {
                            "session_id": session_id, "command": f"source {tcl_word(script)}",
                            "capture_log": True,
                        })
                        while not (directory / "finished.txt").exists():
                            if monotonic() >= deadline:
                                raise TimeoutError("Vivado synthesis monitoring deadline exceeded")
                            await call("vivado_status", {"session_id": session_id})
                            await asyncio.sleep(2)
                        if "vivado_log_messages" in {tool.name for tool in listing.tools}:
                            messages = await call("vivado_log_messages", {
                                "session_id": session_id, "filter": "errors", "max_messages": 20,
                            })
                            (directory / "vivado_messages.json").write_text(
                                json.dumps(messages, ensure_ascii=False, indent=2),
                                encoding="utf-8",
                            )
                    finally:
                        await call("vivado_stop", {
                            "session_id": session_id, "close_vivado": True,
                        }, cleanup=True)


def find_session_id(payload):
    if isinstance(payload, dict):
        if isinstance(payload.get("session_id"), str):
            return payload["session_id"]
        for value in payload.values():
            try:
                return find_session_id(value)
            except ValueError:
                pass
    elif isinstance(payload, list):
        for value in payload:
            try:
                return find_session_id(value)
            except ValueError:
                pass
    elif isinstance(payload, str):
        try:
            parsed = json.loads(payload)
        except ValueError:
            parsed = None
        if isinstance(parsed, (dict, list)):
            return find_session_id(parsed)
        match = re.search(r"session_id[\s\"':=]+([A-Za-z0-9_.-]+)", payload)
        if match:
            return match[1]
    raise ValueError("Ross vivado_start returned no session_id; inspect mcp_calls.jsonl")


def exception_messages(error):
    nested = getattr(error, "exceptions", ())
    if nested:
        return [item for child in nested for item in exception_messages(child)]
    return [f"{type(error).__name__}: {str(error)[:2000]}"]
